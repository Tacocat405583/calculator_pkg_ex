class Calculator:
    def __init__(self):
        print("I am a Calculator")

    def add(self, num1, num2):
        return num1 + num2

    def subtract(self, num1, num2):
        return num1 - num2

    def multiply(self, num1, num2):
        return num1 * num2

    def devide(self, num1, num2):
        return num1 / num2
